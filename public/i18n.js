// 소비자 화면 언어. 한국어 원문은 index.html과 KO 사전에, 영어는 EN 사전에 둔다.
// 정적 문구는 data-i18n(내용)·data-i18n-placeholder·data-i18n-aria 키로 바꾸고, 한국어는 처음 HTML에서 읽어 둔다.
const KEY = "sieve.lang";
export const LANGS = ["ko", "en"];
export let lang = LANGS.includes(localStorage.getItem(KEY)) ? localStorage.getItem(KEY) : "ko";

const listeners = [];
export const onLangChange = (fn) => listeners.push(fn);

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  localStorage.setItem(KEY, lang);
  applyStatic();
  for (const fn of listeners) fn(lang);
}

// 코드북·카테고리처럼 {ko, en} 필드를 가진 객체의 표시명
export const pick = (obj) => obj?.[lang] ?? obj?.ko ?? obj?.en ?? obj?.code ?? "";

export function t(key, ...args) {
  const v = DICT[lang][key] ?? DICT.ko[key] ?? key;
  return typeof v === "function" ? v(...args) : v;
}

const ATTRS = [["i18n", null], ["i18nPlaceholder", "placeholder"], ["i18nAria", "aria-label"]];

export function applyStatic() {
  document.documentElement.lang = lang;
  for (const [data, attr] of ATTRS) {
    const sel = `[data-${data.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}]`;
    for (const el of document.querySelectorAll(sel)) {
      const store = `${data}Ko`;
      if (el.dataset[store] === undefined) el.dataset[store] = attr ? el.getAttribute(attr) ?? "" : el.innerHTML;
      const value = lang === "ko" ? el.dataset[store] : EN_STATIC[el.dataset[data]] ?? el.dataset[store];
      if (attr) el.setAttribute(attr, value); else el.innerHTML = value;
    }
  }
  for (const b of document.querySelectorAll(".lang-switch button")) b.setAttribute("aria-pressed", String(b.lang === lang));
}

